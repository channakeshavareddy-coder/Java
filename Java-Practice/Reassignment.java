/*
 - Problem
 -
 - Write a Java program that declares an integer variable with the value 10, changes its value to 20, and prints the updated value.
 -
 -         Input
 -
 - This problem does not require any input.
 -
 -         Output
 -
 - Print the updated value of the variable.
 -
 -       Expected Output
 -
 - 20
 -
 - Requirement
 -
 - Declare an integer variable.
 - Assign 10 to the variable.
 - Change the variable's value to 20.
 - Print the updated value.
 -
 - Concept
 -
 - Variable reassignment.
 */
public class Reassignment{
    public static void main(String[]args){
        int num = 10;
        num = 20;
        System.out.println(num);
    }
}