/*
 - Requirement: Raju has 25 marks stored as an int. Convert the value to double and display the result.
 -
 -       Output:
 -
 -       25.0
 -
 - Concept: Widening type casting (int → double).
 */
public class WideningCasting{
    public static void main(String[]args){
        int Marks = 25;
        double temp = Marks;
        System.out.println(temp);
    }
}