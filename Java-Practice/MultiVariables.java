/*
 - Problem
 - Write a Java program that declares three integer variables, assigns the values 10, 20, and 30, and prints all three values.
 -
 -         Input
 -
 - This problem does not require any input.
 -
 -         Output
 -
 - Print the three values, each on a separate line.
 -
 - Expected Output
 -
 - 10
 - 20
 - 30
 -
 - Requirement
 -
 - Declare three integer variables.
 - Assign 10, 20, and 30 respectively.
 - Print each variable on a separate line.
 */
public class MultiVariables{
    public static void main(String[]args){
        int num1 = 10;
        int num2 = 20;
        int num3 = 30;
        System.out.println(num1);
        System.out.println(num2);
        System.out.println(num3);
    }
}