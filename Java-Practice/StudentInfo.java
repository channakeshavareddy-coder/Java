/*
 - Requirement: Write a Java program to store and display a student's name, age, grade, pass status, and section using appropriate data types.
 -
 -
 - Input: No input required.
 -
 -      Output:
 -
 - Name: Channakeshavareddy G N
 - Age: 24
 - Grade: 8.25
 - Passed: true
 - Section: A
 -
 - Concept: String, int, double, boolean, and char.
 */
public class StudentInfo{
    public static void main(String[]args){
        String Name = "Channakeshavareddy G N";
        int Age = 24;
        double Grade = 8.25;
        boolean Passed = true;
        char Section = 'A';
        System.out.println(Name);
        System.out.println(Age);
        System.out.println(Grade);
        System.out.println(Passed);
        System.out.println(Section);
    }
}